"""Build src/i18n_data.js from the translation dictionaries.
- en.json / ja.json: { zh-Hant source text: translation }   (edit these; first run seeds them from en.py / ja.py)
- zh-Hans is generated with OpenCC (tw2sp: phrase-level Taiwan→Mainland conversion) plus a per-character map
  used for dynamic text such as player names."""
import json, os, re, glob, importlib
import opencc
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
keys = json.load(open(os.path.join(HERE, 'keys.json')))
EXTRA = {   # strings built in ways the extractor cannot see (nested templates, confirm dialogs)
  '現在離開會判輸{0}。確定要離開嗎？': {'en': 'Leaving now counts as a loss{0}. Are you sure?', 'ja': '今退出すると敗北になります{0}。本当に退出しますか？'},
  '，下注的 {0} 金幣不會退還': {'en': ', and your {0}-coin wager will not be returned', 'ja': '。ベットした {0} コインは戻りません'},
  '：': {'en': ': ', 'ja': '：'},
}
dicts = {}
for lang, mod, var in (('en', 'en', 'EN'), ('ja', 'ja', 'JA')):
    path = os.path.join(HERE, lang + '.json')
    d = json.load(open(path)) if os.path.exists(path) else {}
    if not d:
        arr = getattr(importlib.import_module(mod), var)
        assert len(arr) == len(keys), (lang, len(arr), len(keys))
        d = dict(zip(keys, arr))
    for k, v in EXTRA.items(): d.setdefault(k, v[lang])
    missing = [k for k in keys if k not in d]
    if missing: print(lang, 'missing', len(missing), missing[:5])
    json.dump(d, open(path, 'w'), ensure_ascii=False, indent=0)
    dicts[lang] = {k: v for k, v in d.items() if v != k}
cc = opencc.OpenCC('tw2sp'); cs = opencc.OpenCC('t2s')
hans = {}
for k in keys + list(EXTRA):
    v = cc.convert(k)
    if v != k: hans[k] = v
FIX = [('帐号', '账号'), ('暱', '昵'), ('帐户', '账户')]   # mainland-standard forms OpenCC leaves as variants
for k in list(hans):
    for x, y in FIX: hans[k] = hans[k].replace(x, y)
for k in keys:
    if k not in hans and any(x[0] in cc.convert(k) for x in FIX):
        v = cc.convert(k)
        for x, y in FIX: v = v.replace(x, y)
        hans[k] = v
dicts['zh-Hans'] = hans
# per-character fallback for anything dynamic
chars = set()
for f in glob.glob(os.path.join(ROOT, 'src', '*.js')) + [os.path.join(ROOT, 'index.html')]:
    chars |= set(re.findall(r'[㐀-鿿]', open(f).read()))
cmap = {c: cs.convert(c) for c in sorted(chars) if cs.convert(c) != c and len(cs.convert(c)) == 1}
cmap['暱'] = '昵'
out = '/* generated by i18n/build.py — do not edit by hand */\nconst I18N_DICT = ' + json.dumps(dicts, ensure_ascii=False, separators=(',', ':')) + ';\nconst I18N_T2S = ' + json.dumps(''.join(k + v for k, v in cmap.items()), ensure_ascii=False) + ';\n'
open(os.path.join(ROOT, 'src', 'i18n_data.js'), 'w').write(out)
print('wrote', {k: len(v) for k, v in dicts.items()}, 'chars', len(cmap), 'bytes', len(out.encode()))
